function snakeReply(): string {
  return `老板，别慌，先稳住，我陪你一步一步处理，你自己先别乱动乱跑。

1. 现在马上打 120：告诉接线员“被蛇咬了”，咬在哪个位置、大概多久了、人现在有没有头晕/心慌/呼吸困难；旁边有人的话让他打，你尽量保持不动。
2. 立刻坐下或躺下，让被咬的肢体低于心脏、尽量少动；不要走路、跑动，也不要自己开车。
3. 摘掉伤口附近的手表、戒指、紧身衣物，避免肿胀后卡住影响供血。
4. 用流动清水冲洗伤口，再用干净纱布或布轻轻盖住；不要切开、不要挤压、不要用嘴吸。
5. 能安全拍到蛇就拍下来，拍不到就记颜色、花纹、头型和大小，后面直接告诉医生。
6. 尽快去最近的医院急诊，路上继续让伤肢少动。

⚠️ 千万别做：用嘴吸、切开伤口、扎止血带、冰敷、喝酒止痛、追打或抓蛇。
即使现在不疼不肿也不能拖，有些毒蛇咬伤早期没有明显症状。

请立即拨打 120 / 119 / 110，以专业救援或医生判断为准。需要我把这段话整理成给接线员的简短口述吗？`;
}

function animalBiteReply(): string {
  return `老板，被咬伤/抓伤先别慌，处理好伤口和疫苗这两件事：

1. 用流动清水和肥皂冲洗伤口 15 分钟以上，把表面的唾液、脏物尽量冲掉。
2. 如果出血，用干净纱布或布直接按压止血；不要用嘴吸，不要往伤口撒药粉。
3. 请立即拨打 120，或尽快去最近的医院急诊/犬伤门诊，评估是否需要狂犬疫苗、破伤风针。
4. 记下动物的种类、体型、颜色、是否流浪、有没有疫苗本；如果是家养动物，问清楚疫苗接种情况。
5. 不要因为伤口小就拖着不去，动物咬伤感染和狂犬风险不能凭肉眼判断。

请立即拨打 120 / 119 / 110，以专业救援或医生判断为准。伤口现在出血多吗？能不能确认是什么动物咬的？`;
}

function fireReply(): string {
  return `老板，先保命，再处理其他，马上按这个顺序做：

1. 立刻离开火场，先逃生再报警；请立即拨打 119（有伤情同时打 120）。
2. 逃生时用湿布或衣物捂住口鼻、压低身体走，不乘电梯，不返回去拿东西。
3. 如果门外有浓烟，先摸门把手确认温度；烫就不要开门，用湿布堵门缝、到窗口呼救。
4. 到安全地点后清点人数，告诉消防员有没有人还在里面、大概在哪个位置。
5. 身上着火：停、倒、滚，用厚衣物或毯子压灭，不要跑。

请立即拨打 120 / 119 / 110，以专业救援或医生判断为准。你现在安全了吗？安全后告诉我位置，我帮你把需要告知救援的信息列清楚。`;
}

function earthquakeReply(): string {
  return `老板，地震来了先别冲出去，先做好这三秒：

1. 立刻蹲下、护住头颈，躲到坚固的桌子下或承重墙角落；远离窗户、吊灯、玻璃和大件家具。
2. 不要跑动，不要乘电梯；震动停止前先保持掩护姿势。
3. 震动停止后，用安全通道尽快撤离到空旷地带，远离高楼、电线杆和边坡。
4. 如果被困：保持体力，敲击管道或墙壁发出声音，不要持续大喊。
5. 撤离后先确认身边人是否安全，再打 120 / 119 / 110 报告伤情和被困人员位置。

请立即拨打 120 / 119 / 110，以专业救援或医生判断为准。你现在在室内还是室外？方便的话告诉我，我陪你把下一步理清楚。`;
}

function drowningReply(): string {
  return `老板，溺水救援最怕“救人的人也被拖下水”，先保证自己的安全：

1. 立刻大声呼救，并拨打 120 / 119；如果旁边有救生圈、长杆、绳索或漂浮物，优先递过去，不要贸然下水。
2. 把人救上岸后，先判断意识、呼吸：没有反应且没有呼吸，马上按 120 接线员的指导做心肺复苏，不要浪费时间控水。
3. 有呼吸有意识：让伤者侧卧、保暖，观察呼吸和意识变化，等待急救人员。
4. 不要给溺水者喂水、拍背催吐，也不要自己开车送医，除非救护车无法到达。
5. 记录溺水时间、现场情况和已做的处理，交给急救人员。

请立即拨打 120 / 119 / 110，以专业救援或医生判断为准。人在你身边吗？现在还有呼吸和意识吗？`;
}

